"""Shared post-transition inputs and independent observations for native pilots.

These are oracle/compatibility experiments on already annotated resources. They
do not measure whether a fuzzer discovers the lifecycle or generates logins.
"""

import time

from temporal_auth.integrations.adapters import AdapterError
from temporal_auth.integrations.pilot import analyze_observations


COMPARISON = "post-transition-read-v1"


def validate_comparison(comparison, generation):
    if comparison not in (None, COMPARISON) or generation not in ("old", "fresh"):
        raise ValueError("invalid_native_comparison")


def read_schema(adapter, origin):
    """A fixed GET only: native search cannot grant access back to the subject."""
    content = ({"text/plain": {"schema": {"type": "string"}}}
               if adapter.fixture.target == "gitea" else {"application/json": {
                   "schema": {"type": "object", "additionalProperties": True}}})
    return {"openapi": "3.0.3", "info": {"title": COMPARISON, "version": "1"},
            "servers": [{"url": origin}], "paths": {adapter.path: {"get": {
                "operationId": "readProtectedResource", "responses": {
                    str(code): {"description": str(code), "content": content}
                    for code in (200, 400, 401, 403, 404, 422)}}}}}


def prepare(adapter, budget, generation):
    """Same native adapter, preconditions, transition and bound for each driver."""
    old = adapter.login("old")
    before = adapter.read("read_before", old)
    control = adapter.read("control_before", adapter.owner)
    if any(r.status_code != 200 or adapter.marker not in r.text for r in (before, control)):
        raise AdapterError("invalid_matched_preconditions")
    adapter.transition()
    acknowledgement = next(e for e in adapter.recorder.events if e["step"] == "transition")["finished"]
    adapter.verify_transition()
    fresh = adapter.login("fresh")
    not_before = acknowledgement + 0.05
    while (delay := not_before - (budget.clock() - budget.started)) > 0:
        if budget.remaining() <= 0:
            raise RuntimeError("runtime_budget_exhausted")
        time.sleep(min(0.01, delay))
    sessions = {"old": old, "fresh": fresh}
    contract = {"id": COMPARISON, "generation": generation,
                "resource_path": adapter.path, "methods": ["GET"],
                "credentials": ["owner", "subject_" + generation],
                "propagation_bound_seconds": 0, "tolerance_seconds": 0.05,
                "policy_source": adapter.policy_source,
                "acknowledgement_seconds": acknowledgement, "not_before_seconds": not_before,
                "fresh_login_after_transition": True,
                "old_and_fresh_credentials_equal": old == fresh,
                "fixture_isolation": "new process/database per driver invocation",
                "native_per_test_reset": False,
                "lifecycle_generation_measured": False}
    return sessions, contract


def finish(adapter, sessions, contract):
    """Harness probes are costed separately from requests generated by a tool."""
    adapter.read("probe_old", sessions["old"])
    adapter.read("probe_fresh", sessions["fresh"])
    adapter.read("control_after", adapter.owner)
    events = adapter.recorder.events
    controls = analyze_observations(events, adapter.marker, ["old", "fresh"],
                                    not_before=contract["not_before_seconds"], read_path=adapter.path)
    # Only exact, complete GET observations in the intended credential role count.
    # Other native security probes stay in evidence but cannot inflate coverage.
    native = [e for e in events if e["step"] == "native_subject_get"
              and e["path"] == adapter.path and e["method"] == "GET"]
    valid = [e for e in native if not e["error"] and not e["truncated"]
             and e["started"] >= contract["not_before_seconds"]]
    signals = [e["sequence"] for e in valid if adapter.marker in (e["body"] or "")]
    if controls["verdict"] == "inconclusive" or len(valid) != len(native):
        verdict = "inconclusive"
    elif not valid:
        verdict = "not_exercised"
    elif signals:
        verdict = "candidate"  # independent observation; never a native fault label or confirmation
    elif any(e["status"] not in (200, 401, 403, 404) for e in valid):
        verdict = "inconclusive"
    else:
        verdict = "no_violation_observed"
    return {"harness_controls": controls, "subject_get_requests": len(native),
            "valid_subject_get_requests": len(valid), "protected_content_sequences": signals,
            "native_trace_content_verdict": verdict,
            "native_fault_labels_evaluated": False, "clean_confirmation_performed": False}
